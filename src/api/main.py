"""
main.py

Phase 17: Backend API.

A FastAPI backend wrapping the RAG pipeline built in earlier phases. FastAPI
was chosen (as the phase brief suggested) because it gives automatic request
validation (via the Pydantic schemas in schemas.py), automatic interactive
API documentation at /docs, and async support — all with minimal boilerplate
compared to Flask, and without Django's much heavier full-framework footprint
that this project doesn't need.

RATE LIMITING — why it's "appropriate" here, not just boilerplate:
This project hit REAL rate limits from the Gemini API repeatedly during
development (see rag_pipeline.py's generate_with_retry, added after actually
running into 429 errors during evaluation). The backend sits in front of
that same limited resource, so without our own rate limiting, a handful of
enthusiastic API users could exhaust the free-tier quota for everyone in
minutes. We rate-limit the expensive endpoints (/ask, /compare — anything
that calls Gemini) more strictly than the cheap, local-lookup endpoints
(/health, /trials, /papers).

Run locally:
    uvicorn src.api.main:app --reload

Then visit http://127.0.0.1:8000/docs for interactive API documentation
(auto-generated by FastAPI from the Pydantic schemas and docstrings below).
"""

